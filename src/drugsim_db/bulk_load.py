def insert_compounds(session: Session, rows: list[dict[str, Any]]) -> int:
    """Batch-insert ``compound`` rows.

    Args:
        session: An active session, expected to be used inside
            :func:`drugsim_db.audit.audit_context` so the audit trigger has
            attribution to record.
        rows: From :func:`build_compound_row` (or :func:`build_rows`).

    Returns:
        The number of rows inserted (``len(rows)``; SQLAlchemy's executemany
        does not report per-row counts reliably across dialects, so this
        reflects intent rather than a driver-reported count).
    """
    if not rows:
        return 0
    session.execute(_INSERT_COMPOUND_SQL, rows)
    return len(rows)


def insert_compound_descriptors(session: Session, rows: list[dict[str, Any]]) -> int:
    """Batch-insert ``compound_descriptor`` rows. See :func:`insert_compounds`."""
    if not rows:
        return 0
    session.execute(_INSERT_DESCRIPTOR_SQL, rows)
    return len(rows)


def insert_compound_drug_likeness(session: Session, rows: list[dict[str, Any]]) -> int:
    """Batch-insert ``compound_drug_likeness`` rows. See :func:`insert_compounds`."""
    if not rows:
        return 0
    session.execute(_INSERT_DRUG_LIKENESS_SQL, rows)
    return len(rows)


def load_compounds(
    session: Session,
    processed_compounds: list[ProcessedCompound],
    provenance: CompoundProvenance,
    *,
    source_record_ids: Optional[list[Optional[str]]] = None,
) -> BulkLoadResult:
    """Build and insert one batch of already-processed compounds.

    Callers must have already registered ``provenance.toolchain_id`` and
    ``provenance.descriptor_spec_version`` (see :func:`ensure_toolchain` /
    :func:`ensure_descriptor_spec`) and must run this inside
    :func:`drugsim_db.audit.audit_context` for the governed-table audit
    trigger to have attribution to record.

    Args:
        session: An active session.
        processed_compounds: Already-successful pipeline outputs — parse/
            standardisation failures must be quarantined by the caller
            before reaching this function (see module docstring).
        provenance: Shared batch provenance.
        source_record_ids: Per-compound upstream record ids, same length and
            order as ``processed_compounds``. Omit if the source has none.

    Returns:
        Counts of what was inserted.

    Raises:
        ValueError: If ``source_record_ids`` is given with the wrong length
            — a silent off-by-one here would misattribute provenance.
    """
    if source_record_ids is not None and len(source_record_ids) != len(processed_compounds):
        msg = (
            f"source_record_ids length ({len(source_record_ids)}) must match "
            f"processed_compounds length ({len(processed_compounds)})"
        )
        raise ValueError(msg)

    record_ids: list[Optional[str]] = source_record_ids or [None] * len(processed_compounds)

    built = [
        build_rows(processed, provenance, source_record_id=record_id)
        for processed, record_id in zip(processed_compounds, record_ids)
    ]

    compound_rows = [b.compound for b in built]
    descriptor_rows = [b.descriptor for b in built if b.descriptor is not None]
    drug_likeness_rows = [b.drug_likeness for b in built if b.drug_likeness is not None]

    insert_compounds(session, compound_rows)
    insert_compound_descriptors(session, descriptor_rows)
    insert_compound_drug_likeness(session, drug_likeness_rows)

    return BulkLoadResult(
        compounds_loaded=len(compound_rows),
        descriptors_loaded=len(descriptor_rows),
        drug_likeness_loaded=len(drug_likeness_rows),
        mixtures_without_descriptors=sum(1 for p in processed_compounds if p.is_mixture),
    )


def ensure_toolchain(
    session: Session,
    *,
    toolchain_id: str,
    rdkit_version: str,
    python_version: str,
    std_pipeline_ver: str,
) -> None:
    """Register a ``toolchain`` row if it does not already exist.

    Toolchain rows are append-only by convention (P8: nothing deleted or
    silently altered) — ``ON CONFLICT DO NOTHING`` makes re-running this for
    an already-known toolchain a no-op rather than an error, which matters
    for an ETL step that may be re-run.

    Args:
        session: An active session.
        toolchain_id: See :func:`drugsim_core.version.build_toolchain_id`.
        rdkit_version: RDKit version this toolchain pins.
        python_version: Python version this toolchain pins.
        std_pipeline_ver: ``drugsim_chem`` standardisation pipeline version.
    """
    session.execute(
        text(
            "INSERT INTO toolchain (toolchain_id, rdkit_version, "
            "python_version, std_pipeline_ver) "
            "VALUES (:tid, :rdkit, :python, :stdpipe) "
            "ON CONFLICT (toolchain_id) DO NOTHING"
        ),
        {
            "tid": toolchain_id,
            "rdkit": rdkit_version,
            "python": python_version,
            "stdpipe": std_pipeline_ver,
        },
    )


def ensure_descriptor_spec(
    session: Session,
    *,
    descriptor_spec_version: str,
    toolchain_id: str,
    feature_set_id: str,
    descriptor_list: list[str],
    hbd_convention: str = "lipinski",
    hba_convention: str = "lipinski",
    rotb_strict: bool = False,
) -> None:
    """Register a ``descriptor_spec`` row if it does not already exist.

    Args:
        session: An active session.
        descriptor_spec_version: The version string (matches
            ``drugsim_chem.DESCRIPTOR_SPEC_VERSION``).
        toolchain_id: The toolchain this spec was computed under — must
            already exist (see :func:`ensure_toolchain`).
        feature_set_id: See :func:`drugsim_features.compute_feature_set_id`.
        descriptor_list: Descriptor column names this spec covers.
        hbd_convention: Which HBD definition rule evaluation uses. Defaults
            to ``"lipinski"`` — matches ``drugsim_chem.drug_likeness``, which
            always evaluates rules against the ``*_lipinski`` fields, never
            ``*_strict`` (Phase 1 Step 4 §E.1 correction).
        hba_convention: As above, for HBA.
        rotb_strict: Whether rotatable-bond counting uses RDKit's strict
            definition. Defaults to ``False`` — ``compute_descriptors`` uses
            ``Lipinski.NumRotatableBonds``, the non-strict count.
    """
    session.execute(
        text(
            "INSERT INTO descriptor_spec (descriptor_spec_version, "
            "toolchain_id, hbd_convention, hba_convention, rotb_strict, "
            "descriptor_list, feature_set_id) "
            "VALUES (:version, :tid, :hbd, :hba, :rotb, :dlist, :fsid) "
            "ON CONFLICT (descriptor_spec_version) DO NOTHING"
        ),
        {
            "version": descriptor_spec_version,
            "tid": toolchain_id,
            "hbd": hbd_convention,
            "hba": hba_convention,
            "rotb": rotb_strict,
            "dlist": descriptor_list,
            "fsid": feature_set_id,
        },
    )
