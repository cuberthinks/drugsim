"""Bulk-load processed compounds into ``compound`` / ``compound_descriptor`` /
``compound_drug_likeness``.

Split the same way as ``registry_sync``/``snapshots``: ``build_*`` functions
are pure (a :class:`~drugsim_chem.pipeline.ProcessedCompound` plus caller-
supplied provenance in, a row dict out — testable with no database) and
``insert_*`` functions are thin, batched inserts.

Scope note: this module assumes each ``ProcessedCompound`` it is given
already succeeded through :func:`drugsim_chem.process_structure` — parse/
standardisation failures are quarantined by the caller *before* reaching
here (that is what makes ``StructureError`` the quarantine signal per the
project's "invalid molecules must be rejected or quarantined" rule). This
module's only job is turning an already-valid processed compound into rows.

``mol`` and ``morgan_fp_r2_2048`` are generated by the RDKit Postgres
cartridge from ``standardized_smiles`` inside the INSERT itself
(``mol_from_smiles``/``morganbv_fp``), not serialised from Python RDKit
objects — the same approach already used by
``tests/constraints/factories.py``. This keeps a second, Python-side RDKit
serialisation path from ever being able to drift from what the cartridge
itself would produce from the same SMILES.

Known limitation (flagged, not fixed, in Phase 2 — see the Phase 2 completion
report): ``identity.inchikey_full`` is computed on the *standardised*
(salt-stripped, charge-neutral) structure (Sprint 2.5/2.6), which is the same
structure ``parent_inchikey`` is meant to represent (Phase 1 Step 2 §5: "Exact
... Deduplication of identical entities" vs "Parent ... Links salt forms to
parent"). In the current pipeline the two coincide whenever a parent is
identified, so two different salt forms of the same active ingredient would
collide on ``uq_compound_inchikey`` instead of being stored as distinct
entities linked by a shared ``parent_inchikey``. This module reproduces that
existing pipeline behaviour rather than inventing a divergent one during a
bulk-load change; resolving it requires computing an entity-level identity
before salt stripping, which is a chemistry-pipeline change, not a loader
change, and is recommended for early Phase 3 before ingesting sources
(ChEMBL/BindingDB) where salt-form duplication is common.
"""

from __future__ import annotations

from dataclasses import dataclass
