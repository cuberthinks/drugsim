@dataclass(frozen=True)
class CompoundProvenance:
    """Provenance fields shared by every row in one bulk-load batch.

    One value per load run: a single ETL run ingests from one source and one
    snapshot, under one toolchain and one descriptor spec, at one
    pipeline/application version — so these are supplied once here rather
    than threaded individually through every row-building call.

    Attributes:
        source_id: ``data_source.source_id`` this batch was ingested from.
        snapshot_id: ``ingestion_snapshot.snapshot_id`` the raw bytes were
            landed under (Sprint 2.4) — the provenance link back to the
            immutable Z1 file this batch was parsed from.
        source_license: The licence text as it stood at acquisition (kept
            per-row, not looked up from the registry's current value, so a
            later relicensing does not retroactively change the terms this
            record was ingested under).
        license_tier: One of ``license_tier_t`` (``green``/``amber``/``red``/
            ``black``).
        is_commercial_ok: Whether this source's licence permits commercial
            use.
        toolchain_id: The ``toolchain`` row these compounds were computed
            under (RDKit + Python + standardisation pipeline versions).
        descriptor_spec_version: The ``descriptor_spec`` row these
            descriptors were computed under.
        pipeline_version: Git SHA of the ETL code performing this load.
        drugsim_release: Application semver at load time.
        created_by: ``system_user.user_uid`` attributed with creating these
            rows — use :data:`drugsim_core.ids.SYSTEM_USER_UID` for an
            unattended batch load.
    """

    source_id: str
    snapshot_id: str
    source_license: str
    license_tier: str
    is_commercial_ok: bool
    toolchain_id: str
    descriptor_spec_version: str
    pipeline_version: str
    drugsim_release: str
    created_by: str


@dataclass(frozen=True)
class BuiltRows:
    """The rows built for one processed compound.

    Attributes:
        compound: Always present.
        descriptor: ``None`` for a flagged mixture — there is nothing to
            insert, matching ``ProcessedCompound.descriptors`` being
            ``None`` for the same reason.
        drug_likeness: ``None`` alongside ``descriptor`` for the same
            reason.
    """

    compound: dict[str, Any]
    descriptor: Optional[dict[str, Any]]
    drug_likeness: Optional[dict[str, Any]]


@dataclass(frozen=True)
class BulkLoadResult:
    """Counts from one :func:`load_compounds` call."""

    compounds_loaded: int
    descriptors_loaded: int
    drug_likeness_loaded: int
    mixtures_without_descriptors: int


def build_compound_row(
    processed: ProcessedCompound,
    provenance: CompoundProvenance,
    *,
    source_record_id: Optional[str] = None,
    compound_uid: Optional[str] = None,
) -> dict[str, Any]:
    """Build the ``compound`` row for one processed compound.

    Args:
        processed: Output of :func:`drugsim_chem.process_structure`.
        provenance: Shared batch provenance.
        source_record_id: The upstream source's own record id for this
            compound, if the source has one (e.g. a ChEMBL molecule id).
        compound_uid: Surrogate key. Generated if omitted — callers doing
            deterministic testing should supply one explicitly.

    Returns:
        A dict of column values ready to bind into an INSERT.
    """
    identity = processed.identity
    has_parent = processed.parent_smiles is not None
    return {
        "compound_uid": compound_uid or generate_ulid(),
        "source_smiles": processed.source_smiles,
        "canonical_smiles": identity.canonical_smiles,
        "isomeric_smiles": identity.isomeric_smiles,
        "standardized_smiles": processed.standardized_smiles,
        "parent_smiles": processed.parent_smiles,
        "inchi": identity.inchi,
        "inchikey_full": identity.inchikey_full,
        "inchikey_skeleton": identity.inchikey_skeleton,
        # See module docstring's "Known limitation" note: inchikey_full and
        # parent_inchikey coincide today because identity is computed on the
        # already-salt-stripped structure.
        "parent_inchikey": identity.inchikey_full if has_parent else None,
        "molecular_formula": identity.molecular_formula,
        "bemis_murcko_scaffold": identity.bemis_murcko_scaffold,
        "stereo_completeness": processed.stereo_completeness,
        "standardization_flags": list(processed.standardization.flags),
        "component_count": processed.standardization.component_count,
        "is_mixture": processed.is_mixture,
        "source_id": provenance.source_id,
        "source_record_id": source_record_id,
        "snapshot_id": provenance.snapshot_id,
        "source_license": provenance.source_license,
        "license_tier": provenance.license_tier,
        "is_commercial_ok": provenance.is_commercial_ok,
        "toolchain_id": provenance.toolchain_id,
        "pipeline_version": provenance.pipeline_version,
        "drugsim_release": provenance.drugsim_release,
        "created_by": provenance.created_by,
    }


def build_descriptor_row(
    compound_uid: str,
    processed: ProcessedCompound,
    provenance: CompoundProvenance,
) -> Optional[dict[str, Any]]:
    """Build the ``compound_descriptor`` row, or ``None`` for a mixture.

    Args:
        compound_uid: The compound this descriptor set belongs to — must
            match the ``compound_uid`` used in the corresponding
            :func:`build_compound_row` call.
        processed: Output of :func:`drugsim_chem.process_structure`.
        provenance: Shared batch provenance.

    Returns:
        A row dict, or ``None`` when ``processed.descriptors is None``
        (flagged mixture — there is no well-defined single structure to
        describe).
    """
    d = processed.descriptors
    if d is None:
        return None
    return {
        "compound_uid": compound_uid,
        "descriptor_spec_version": provenance.descriptor_spec_version,
        "mw_g_mol": d.mw_g_mol,
        "mw_parent_g_mol": d.mw_parent_g_mol,
        "exact_mass_g_mol": d.exact_mass_g_mol,
        "logp_crippen": d.logp_crippen,
        "molar_refractivity": d.molar_refractivity,
        "tpsa_a2": d.tpsa_a2,
        "rotatable_bonds": d.rotatable_bonds,
        "aromatic_rings": d.aromatic_rings,
        "ring_count": d.ring_count,
        "heavy_atom_count": d.heavy_atom_count,
        "formal_charge": d.formal_charge,
        "hbd_lipinski": d.hbd_lipinski,
        "hba_lipinski": d.hba_lipinski,
        "hbd_strict": d.hbd_strict,
        "hba_strict": d.hba_strict,
        "heteroatom_count": d.heteroatom_count,
        "fraction_csp3": d.fraction_csp3,
        "num_stereocentres": d.num_stereocentres,
        "largest_ring_size": d.largest_ring_size,
    }


def build_drug_likeness_row(
    compound_uid: str,
    processed: ProcessedCompound,
    provenance: CompoundProvenance,
) -> Optional[dict[str, Any]]:
    """Build the ``compound_drug_likeness`` row, or ``None`` for a mixture.

    Args:
        compound_uid: The compound this verdict set belongs to.
        processed: Output of :func:`drugsim_chem.process_structure`.
        provenance: Shared batch provenance.

    Returns:
        A row dict, or ``None`` when ``processed.drug_likeness is None``.
    """
    dl = processed.drug_likeness
    if dl is None:
        return None
    return {
        "compound_uid": compound_uid,
        "descriptor_spec_version": provenance.descriptor_spec_version,
        "lipinski_violations": dl.lipinski_violations,
        "lipinski_pass": dl.lipinski_pass,
        "veber_pass": dl.veber_pass,
        "ghose_pass": dl.ghose_pass,
        "egan_pass": dl.egan_pass,
        "muegge_pass": dl.muegge_pass,
        "rule_of_three_pass": dl.rule_of_three_pass,
        "bioavailability_score": dl.bioavailability_score,
        "qed_score": dl.qed_score,
        "sa_score": dl.sa_score,
        "np_likeness_score": dl.np_likeness_score,
        "pains_alerts": dl.pains_alerts,
        "brenk_alerts": dl.brenk_alerts,
        "pfizer_3_75_flag": dl.pfizer_3_75_flag,
        "gsk_4_400_flag": dl.gsk_4_400_flag,
    }


def build_rows(
    processed: ProcessedCompound,
    provenance: CompoundProvenance,
    *,
    source_record_id: Optional[str] = None,
    compound_uid: Optional[str] = None,
) -> BuiltRows:
    """Build all three rows for one processed compound in one call.

    Args:
        processed: Output of :func:`drugsim_chem.process_structure`.
        provenance: Shared batch provenance.
        source_record_id: The upstream source's own record id, if any.
        compound_uid: Surrogate key. Generated if omitted.

    Returns:
        The built rows, with ``descriptor``/``drug_likeness`` as ``None``
        for a flagged mixture.
    """
    compound_row = build_compound_row(
        processed, provenance, source_record_id=source_record_id, compound_uid=compound_uid
    )
    uid = compound_row["compound_uid"]
    return BuiltRows(
        compound=compound_row,
        descriptor=build_descriptor_row(uid, processed, provenance),
        drug_likeness=build_drug_likeness_row(uid, processed, provenance),
    )


_INSERT_COMPOUND_SQL = text(
    "INSERT INTO compound (compound_uid, source_smiles, canonical_smiles, "
    "isomeric_smiles, standardized_smiles, parent_smiles, inchi, "
    "inchikey_full, inchikey_skeleton, parent_inchikey, molecular_formula, "
    "bemis_murcko_scaffold, stereo_completeness, standardization_flags, "
    "component_count, is_mixture, mol, morgan_fp_r2_2048, source_id, "
    "source_record_id, snapshot_id, source_license, license_tier, "
    "is_commercial_ok, toolchain_id, pipeline_version, drugsim_release, "
    "created_by) "
    "VALUES (:compound_uid, :source_smiles, :canonical_smiles, "
    ":isomeric_smiles, :standardized_smiles, :parent_smiles, :inchi, "
    ":inchikey_full, :inchikey_skeleton, :parent_inchikey, "
    ":molecular_formula, :bemis_murcko_scaffold, :stereo_completeness, "
    ":standardization_flags, :component_count, :is_mixture, "
    "mol_from_smiles(:standardized_smiles), "
    "morganbv_fp(mol_from_smiles(:standardized_smiles), 2), :source_id, "
    ":source_record_id, :snapshot_id, :source_license, :license_tier, "
    ":is_commercial_ok, :toolchain_id, :pipeline_version, :drugsim_release, "
    ":created_by)"
)

